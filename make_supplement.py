#!/usr/bin/env python3
"""make_supplement.py -- writes supplementary.tex with every code file reproduced inline (no \\input needed), the
manifest of the run that produced the manuscript numbers, and the test-suite output."""
import hashlib
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FILES = [
    ("psdf_core.py", "Simulation engine: configuration, random environment, outcome-based weight estimators, AHP, one replication, statistics."),
    ("run_experiments.py", "Experiment runner: baseline, ablation, partial feedback, noise sensitivity, factorial regime maps; writes CSV, LaTeX tables and number macros."),
    ("seed_robustness.py", "Repeats the baseline under independent master seeds (Monte Carlo stability of the paired contrasts)."),
    ("test_temporal_integrity.py", "Temporal-integrity and sanity tests (Section 6.2 of the manuscript)."),
    ("build_panel.py", "Builds the balanced 77-province x 45-month panel from the three MOTS provincial workbooks and reproduces the consistency checks of Section 11.1."),
    ("empirical_tourism.py", "Empirical application of Section 11: features, outcome, PSDF variants and benchmarks, moving-block bootstrap; writes Table 12 and the number macros."),
    ("test_empirical.py", "Tests of the empirical script (no future information in decisions, outcome standardisation, end-to-end output)."),
    ("make_prov_csv.py", "Extracts the 77 provincial 2024 feature inputs of the semi-synthetic environment from the compiled data table and checks them against the published national totals."),
    ("run_all.sh", "Single command that reproduces everything."),
]


def esc(s):
    return s.replace("_", r"\_")


def listing(path, caption):
    src = open(os.path.join(HERE, path), encoding="utf-8").read().rstrip("\n")
    assert "\\end{lstlisting}" not in src
    return (f"\\subsection{{\\texttt{{{esc(path)}}}}}\n{caption}\\par\\smallskip\n"
            f"\\noindent SHA-256: \\texttt{{{hashlib.sha256(open(os.path.join(HERE, path), 'rb').read()).hexdigest()}}}\\par\n"
            f"\\begin{{lstlisting}}[language=Python,caption={{{esc(path)}}}]\n{src}\n\\end{{lstlisting}}\n")


def main():
    man = json.load(open(os.path.join(HERE, "results", "manifest.json")))
    tests = "\n".join(subprocess.run([sys.executable, f], cwd=HERE, capture_output=True, text=True).stdout.strip() for f in ("test_temporal_integrity.py", "test_empirical.py"))
    tests = "\n".join(l for l in tests.splitlines() if l.startswith(("PASS", "FAIL")) or "failure" in l)
    panel_sha = hashlib.sha256(open(os.path.join(HERE, "panel.csv"), "rb").read()).hexdigest()
    out = r"""\documentclass[10pt,a4paper]{article}
\usepackage[T1]{fontenc}\usepackage[utf8]{inputenc}
\usepackage[margin=2cm]{geometry}\usepackage{xcolor}\usepackage{listings}\usepackage{booktabs}
\usepackage[colorlinks=true,linkcolor=blue!50!black,urlcolor=blue!50!black]{hyperref}
\lstset{basicstyle=\ttfamily\scriptsize,numbers=left,numberstyle=\tiny\color{gray},breaklines=true,breakatwhitespace=false,
  columns=fullflexible,keepspaces=true,frame=single,framerule=0.2pt,showstringspaces=false,tabsize=4,
  keywordstyle=\color{blue!60!black},commentstyle=\color{green!40!black}\itshape,stringstyle=\color{red!50!black},
  literate={\ \ }{{\ }}1}
\title{Supplementary Material\\ \large Code and reproduction instructions for\\
``When Does Feedback-Driven Weighting Outperform Preference Elicitation? Evidence from Simulation and Empirical Evaluation''}
\author{Patcharaporn Samarnggoon}
\date{}
\begin{document}\maketitle
\section{Overview}
This file contains, in full, the code that generates every synthetic-environment result reported in Section~10 of the
manuscript (Tables~3--9 and~11, the AHP diagnostics, the noise and partial-feedback experiments, and the Monte Carlo
stability analysis). The empirical application (Table~12) is regenerated by \texttt{build\_panel.py} and \texttt{empirical\_tourism.py} from the three MOTS provincial workbooks (instructions below). All numbers in those tables and in the corresponding text are written by the code into LaTeX files
(\texttt{results/tex/*.tex}, \texttt{results/macros.tex}) stamped with a single run identifier, so the manuscript and the code
cannot drift apart.

\paragraph{Reproduction.} Python $\ge 3.10$ with \texttt{numpy} and \texttt{scipy} (no other dependencies). From the
directory containing the files below run \texttt{sh run\_all.sh}. This runs the test suite, all experiments (about two minutes
on a laptop) and the 20-seed stability analysis. The manuscript is then compiled with \texttt{pdflatex main.tex} (twice).

\paragraph{Run that produced the manuscript.}
\begin{tabular}{ll}
Run identifier & \texttt{""" + man["run_id"] + r"""}\\
Master seed & """ + str(man["seed"]) + r"""\\
Replications & """ + str(man["config"]["R"]) + r"""\\
Bootstrap resamples (baseline / factorial) & """ + f"{man['boot']:,} / {man['boot_factorial']:,}".replace(",", "{,}") + r"""\\
Protocol-conformant run & """ + str(man["protocol_conformant"]) + r"""\\
Python / NumPy / SciPy & """ + f"{man['python']} / {man['numpy']} / {man['scipy']}" + r"""\\
Semi-synthetic regime map included in this run & """ + ("yes" if man["semi_synthetic_run"] else "no (requires the provincial feature file, see below)") + r"""\\
Code SHA-256 (concatenated files) & \texttt{""" + man["code_sha256"][:32] + r"""\ldots}\\
\end{tabular}

\paragraph{Random streams.} \texttt{numpy.random.SeedSequence(seed).spawn(R)} gives one child per replication; each child
spawns five independent streams (features, outcome/label noise, AHP judgment noise, feedback-mask keys, preference-gap
direction). All methods and all experimental cells of a replication therefore see identical generated environments, and the
feedback-rate conditions use nested observation sets.

\paragraph{Semi-synthetic environment.} \texttt{run\_experiments.py --features prov.csv} adds the semi-synthetic regime map
(Table~10). The file \texttt{prov.csv} is produced by \texttt{make\_prov\_csv.py}. The CSV has one row per province with columns \texttt{visitors\_total}, \texttt{visitors\_foreign},
\texttt{receipts\_total} (2024 values); the three features are $\log$ visits, $\log$ receipts per visit and the foreign share,
min--max scaled.

\paragraph{Empirical application.} \texttt{python build\_panel.py mots2024.xlsx mots2025.xlsx mots2026.xlsx panel.csv prov.csv} builds the balanced 77-province $\times$ 45-month panel from the three MOTS provincial workbooks (previous-year columns of the 2024 sheets supply 2023) and prints the checks of Section~11.1: no missing values, Thai plus foreign equals total, 924/924 and 693/693 identical overlapping province-months, 2024 provincial sums equal to the published annual totals, and January 2025 provincial sums equal to the national row. \texttt{python empirical\_tourism.py panel.csv} then writes Table~12 (\texttt{results\_empirical/}). SHA-256 of the \texttt{panel.csv} used for the manuscript: \texttt{""" + panel_sha + r"""}.

\paragraph{Test suite output.}
\begin{lstlisting}[numbers=none]
""" + tests + r"""
\end{lstlisting}

\paragraph{Files.}
\begin{tabular}{ll}
\toprule File & Purpose\\\midrule
""" + "\n".join(f"\\texttt{{{esc(f)}}} & {d}\\\\" for f, d in FILES) + r"""
\bottomrule\end{tabular}

\section{Source code}
""" + "\n".join(listing(f, d) for f, d in FILES) + r"""
\section{Run manifest}
\begin{lstlisting}[numbers=none]
""" + json.dumps(man, indent=2) + r"""
\end{lstlisting}
\end{document}
"""
    open(os.path.join(HERE, "supplementary.tex"), "w", encoding="utf-8").write(out)
    print("wrote supplementary.tex", len(out))


if __name__ == "__main__":
    main()
